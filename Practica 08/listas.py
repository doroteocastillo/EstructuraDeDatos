# Lista de capacidad lógica inicial
numeros = [10, 20, 30, 40, 50]

print("Lista original:", numeros)

# Agregar un elemento
numeros.append(60)

print("Después de agregar:", numeros)

# Eliminar un elemento
numeros.remove(30)

print("Después de eliminar:", numeros)

# Consultar cantidad de elementos
print("Cantidad:", len(numeros))